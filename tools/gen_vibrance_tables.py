# -*- coding: utf-8 -*-
"""把 vibrance-cal/vibrance_model.json 里的标定参数导出成 C 表头。

    python tools/gen_vibrance_tables.py [模型路径] [-o 输出路径]

默认读 ../vibrance-cal/vibrance_model.json，写 ops/vibrance-ps/vibrance-tables.h。

为什么要重采样：模型里每条曲线的 S 采样点并不统一（v=5 只有 5 个点，v=100 有
9 个），而算子要按像素做双线性插值，必须有一张公共网格。这里用与
vibrance_ref.py 完全相同的规则（端点外取端点值、区间内线性）把每档曲线重采样
到公共网格上，所以 C 端和 Python 参考实现算出来的数字是同一套。
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_MODEL = os.path.join(os.path.dirname(ROOT), "vibrance-cal", "vibrance_model.json")
DEFAULT_OUT = os.path.join(ROOT, "ops", "vibrance-ps", "vibrance-tables.h")

# 公共 S 网格（百分数）：取各档采样点的并集，再加上两端的 0 / 100，
# 这样原采样点全部落在网格上，重采样不引入额外误差。
S_GRID = [0.0, 17.9, 33.3, 46.4, 57.3, 66.5, 75.0, 82.5, 89.1, 94.6, 100.0]


def interp(keys, vals, x):
    """与 vibrance_ref._interp_table 相同：端点钳制 + 线性插值。"""
    if x <= keys[0]:
        return vals[0]
    if x >= keys[-1]:
        return vals[-1]
    for i in range(1, len(keys)):
        if x <= keys[i]:
            t = (x - keys[i - 1]) / (keys[i] - keys[i - 1])
            return vals[i - 1] + t * (vals[i] - vals[i - 1])
    return vals[-1]


def resample(pairs):
    """[(s%, y), ...] → 公共网格上的 y 值。"""
    keys = [p[0] for p in pairs]
    vals = [p[1] for p in pairs]
    return [interp(keys, vals, s) for s in S_GRID]


def fmt_row(vals, indent="  "):
    return indent + ", ".join("%9.5ff" % v for v in vals)


def main():
    argv = [a for a in sys.argv[1:]]
    out = DEFAULT_OUT
    if "-o" in argv:
        i = argv.index("-o")
        out = argv[i + 1]
        del argv[i:i + 2]
    model_path = argv[0] if argv else DEFAULT_MODEL

    m = json.load(open(model_path, encoding="utf-8"))

    pos = sorted(int(k) for k in m["A"])            # 5 … 100
    neg = sorted(int(k) for k in m["negative_S1"])  # -100 … -5
    assert pos == list(range(5, 101, 5)), pos
    assert neg == list(range(-100, 0, 5)), neg

    A, P, Q = [], [], []
    # 索引 0 代表 v=0：不产生任何变化，指数沿用 v=5 的值保证连续
    A.append(0.0)
    P.append(float(m["p"][str(pos[0])]))
    Q.append(float(m["q"][str(pos[0])]))
    for v in pos:
        A.append(float(m["A"][str(v)]))
        P.append(float(m["p"][str(v)]))
        Q.append(float(m["q"][str(v)]))

    red = []
    for v in pos:
        d = m["red_mask"][str(v)]
        red.append(resample([(float(k), float(x)) for k, x in d.items()]))

    # JSON 里 S' 是百分数，C 端全程用 0-1 的比例，这里先除 100
    neg_s1 = [[y / 100.0 for y in resample(m["negative_S1"][str(v)])] for v in neg]
    neg_v = [resample(m["negative_Vscale"][str(v)]) for v in neg]

    lum = m.get("lum_factor", {})
    lumL = sorted(float(k) for k in lum)
    lumC = [float(lum["%g" % k]) for k in lumL]

    lines = []
    w = lines.append
    w("/* 本文件由 tools/gen_vibrance_tables.py 生成，请勿手工编辑。")
    w(" * Generated by tools/gen_vibrance_tables.py — do not edit by hand.")
    w(" *")
    w(" * 数据来源 / source: %s" % os.path.basename(model_path))
    w(" *   %s" % m["meta"].get("source", ""))
    w(" * 正向 / positive:  dS = A(v)·S^p(v)·(1-S)^q(v)   （S 为 HSV 饱和度 0-1）")
    w(" * 红带 / red band:  v=5..100 每档一条系数曲线，S 以百分数索引")
    w(" * 负向 / negative:  S' 与 V'/V 直接查表，v=-100..-5")
    w(" */")
    w("#ifndef VIB_TABLES_H")
    w("#define VIB_TABLES_H")
    w("")
    w("#define VIB_LEVELS     21   /* v = 0,5,…,100 */")
    w("#define VIB_COLS       11   /* S 采样点个数 / S sample points */")
    w("#define VIB_NEG_LEVELS 20   /* v = -100,…, -5 */")
    w("#define VIB_LUM        5    /* 亮度修正采样点 / lightness samples */")
    w("")
    w("static const gfloat vib_S[VIB_COLS] = {")
    w(fmt_row(S_GRID))
    w("};")
    w("")
    w("/* 索引 i 对应 v = 5i；v=0 的 A 为 0，p/q 沿用 v=5 以保证插值连续。")
    w(" * index i maps to v = 5i. A[0] = 0 and p/q[0] repeat v=5 so the")
    w(" * interpolation stays continuous down to zero. */")
    w("static const gfloat vib_A[VIB_LEVELS] = {")
    w(fmt_row(A))
    w("};")
    w("static const gfloat vib_p[VIB_LEVELS] = {")
    w(fmt_row(P))
    w("};")
    w("static const gfloat vib_q[VIB_LEVELS] = {")
    w(fmt_row(Q))
    w("};")
    w("")
    w("/* 红带保护系数，行 = v=5..100（步长 5），列 = vib_S。")
    w(" * Red-band hold-back, rows v = 5..100 step 5, columns = vib_S. */")
    w("static const gfloat vib_red[VIB_NEG_LEVELS][VIB_COLS] = {")
    for row in red:
        w("  {" + ", ".join("%8.5ff" % v for v in row) + "},")
    w("};")
    w("")
    w("/* 负向：S' 的目标值（行 = v=-100..-5）/ negative: resulting S */")
    w("static const gfloat vib_neg_S1[VIB_NEG_LEVELS][VIB_COLS] = {")
    for row in neg_s1:
        w("  {" + ", ".join("%8.5ff" % v for v in row) + "},")
    w("};")
    w("")
    w("/* 负向：明度比 V'/V / negative: lightness ratio V'/V */")
    w("static const gfloat vib_neg_V[VIB_NEG_LEVELS][VIB_COLS] = {")
    for row in neg_v:
        w("  {" + ", ".join("%8.5ff" % v for v in row) + "},")
    w("};")
    w("")
    w("/* 亮度修正 c(L)：L 为 HSL 明度百分数，浅色拿到的增量更少。")
    w(" * Lightness factor c(L), L in percent of HSL lightness. */")
    w("static const gfloat vib_lumL[VIB_LUM] = {")
    w(fmt_row(lumL))
    w("};")
    w("static const gfloat vib_lumC[VIB_LUM] = {")
    w(fmt_row(lumC))
    w("};")
    w("")
    w("#endif /* VIB_TABLES_H */")

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    print("写出 %s（%d 行）" % (out, len(lines)))
    print("  正向 A(100)=%.5f  p(100)=%.2f  q(100)=%.2f" % (A[-1], P[-1], Q[-1]))
    print("  红带 v=100 @S=46.4: %.4f   负向 v=-100 @S=100: S'=%.3f"
          % (red[-1][3], neg_s1[0][-1]))


if __name__ == "__main__":
    main()
